/**
 * Sidebar themes, the way Slack does them: the colour mode (light/dark/system)
 * decides the message area, and a theme repaints the chrome around it — rail,
 * sidebar, top bar and the active-item highlight.
 *
 * Colours are matched by eye against Slack's swatches, so they are close
 * rather than exact.
 */
export interface ChromeTheme {
  id: string;
  name: string;
  group: string;
  /** Icon rail down the far left. */
  rail: string;
  /** Channel list. */
  sidebar: string;
  /** Top bar with the search box. */
  topbar: string;
  /** Selected channel. */
  active: string;
  text: string;
  muted: string;
  /** Unread badge and mention pill. */
  accent: string;
}

