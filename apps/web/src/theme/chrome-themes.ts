export const DEFAULT_CHROME_THEME_ID = "aubergine";

export function getChromeTheme(id: string): ChromeTheme {
  return (
    CHROME_THEMES.find((t) => t.id === id) ??
    CHROME_THEMES.find((t) => t.id === DEFAULT_CHROME_THEME_ID)!
  );
}

/** CSS custom properties a theme overrides on top of the colour mode. */
export function chromeThemeVariables(theme: ChromeTheme): Record<string, string> {
  return {
    "--rail-bg": theme.rail,
    "--sidebar-bg": theme.sidebar,
    "--topbar-bg": theme.topbar,
    "--sidebar-active": theme.active,
    "--sidebar-text": theme.text,
    "--sidebar-muted": theme.muted,
    "--sidebar-accent": theme.accent,
  };
}
